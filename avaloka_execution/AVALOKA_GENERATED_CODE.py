# STAGE 2: MONSOON RECHARGE GAP COMPUTATION
# =====================================================================
def stage2_monsoon_recharge_gap(df):
    # Filter seasons
    may_df = df[df['season'] == 'Pre-Monsoon Summer (May)'][['station_code', 'district', 'hydro_zone', 'year', 'depth']].rename(columns={'depth': 'depth_may'})
    nov_df = df[df['season'] == 'Post-Monsoon Kharif (November)'][['station_code', 'year', 'depth']].rename(columns={'depth': 'depth_nov'})

    # Inner merge to align station and year
    paired = pd.merge(may_df, nov_df, on=['station_code', 'year'])
    
    # Delta_h = May_depth - Nov_depth (positive = water table rose / recharged)
    paired['recharge_delta'] = paired['depth_may'] - paired['depth_nov']
    paired['recharge_deficit_flag'] = (paired['recharge_delta'] <= 0.0).astype(int)

    # District aggregation
    dist_summary = paired.groupby('district').agg(
        total_paired_records=('recharge_delta', 'count'),
        median_pre_monsoon_depth=('depth_may', 'median'),
        median_recharge_delta=('recharge_delta', 'median'),
        deficit_station_years=('recharge_deficit_flag', 'sum'),
        deficit_percentage=('recharge_deficit_flag', lambda x: x.mean() * 100.0)
    ).reset_index().sort_values('deficit_percentage', ascending=False)

    return paired, dist_summary

