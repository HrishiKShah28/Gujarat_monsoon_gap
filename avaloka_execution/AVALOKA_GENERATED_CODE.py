# STAGE 3: HYDROGEOLOGICAL CASE-MIX (SIMPSON'S PARADOX)
# =====================================================================
def stage3_simpsons_paradox(paired, df):
    # Align January next year for winter Rabi drawdown
    jan_df = df[df['season'] == 'Post-Monsoon Rabi (January)'][['station_code', 'year', 'depth']].copy()
    jan_df['prev_year'] = jan_df['year'] - 1
    
    paired_with_jan = pd.merge(
        paired,
        jan_df[['station_code', 'prev_year', 'depth']].rename(columns={'prev_year': 'year', 'depth': 'depth_jan_next'}),
        on=['station_code', 'year'],
        how='left'
    )
    paired_with_jan['rabi_drawdown'] = paired_with_jan['depth_jan_next'] - paired_with_jan['depth_nov']

    # Group by hydrogeological zone
    case_mix = paired_with_jan.groupby('hydro_zone').agg(
        total_records=('recharge_delta', 'count'),
        median_may_depth=('depth_may', 'median'),
        median_recharge=('recharge_delta', 'median'),
        median_rabi_drawdown=('rabi_drawdown', 'median'),
        deficit_rate=('recharge_deficit_flag', lambda x: x.mean() * 100.0)
    ).reset_index()

    return case_mix

